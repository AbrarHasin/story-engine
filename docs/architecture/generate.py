def _fit(s, size, maxw, what):
    for ln in s.split("\n"):
        if len(ln) * char_w(size) > maxw:
            raise SystemExit("TEXT TOO WIDE (%d px > %d) in %s: %r"
                             % (len(ln) * char_w(size), maxw, what, ln))


def card(x, y, w, h, cat, title, body, accent, status=None, dashed=False,
         title_size=16):
    _fit(title, title_size, w - 30, "title " + title)
    _fit(body or "", 12.5, w - 30, "body of " + title)
    return d.card(x, y, w, h, cat, title, body, accent, status=status,
                  dashed=dashed, title_size=title_size)


def bullets(x, y, items, size=13, maxw=270, color=BODY, step=22):
    for j, b in enumerate(items):
        _fit(b, size, maxw, "bullet")
        d.text(x, y + j * step, b, size, color)


def legend(x, y, w, h, extra_flows):
    d.panel(x, y, w, h, "Legend", INK)
    cx = x + 20
    for label, desc in (("LIVE", "in the code and running"),
                        ("PARTIAL", "code exists, incomplete"),
                        ("PLANNED", "designed, not built"),
                        ("DEFERRED", "decided, postponed")):
        cw = d.chip(cx, y + 44, label, STATUS[label])
        d.text(cx + cw + 8, y + 46, desc, 12.5, BODY)
        cx += cw + 8 + len(desc) * char_w(12.5) + 24
    for i, (col, style, desc) in enumerate(extra_flows):
        fx = x + 20 + (i % 2) * 540
        fy = y + 92 + (i // 2) * 30
        d.line([(fx, fy + 8), (fx + 60, fy + 8)], col, style=style)
        d.text(fx + 72, fy, desc, 12.5, BODY)
    by = y + h - 56
    d.badge(x + 33, by + 12, "4", FLOW_REQUEST)
    d.text(x + 54, by + 4, "Numbered step, explained in the step panel", 12.5, BODY)
